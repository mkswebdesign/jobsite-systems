#!/usr/bin/env node
/**
 * Emit redirect stubs into dist/ for the active brand.
 *
 * Reads:  ../arich-source/content/brands/<BRAND>/redirects.json
 *         shape: { "permanent": [ { "from": "/old/", "to": "/new/" }, ... ] }
 *
 * Emits three formats so universal SFTP coverage works regardless of host:
 *   - dist/_redirects         (Netlify-style: "<from> <to> 301", one per line)
 *   - dist/.htaccess          (Apache: "Redirect 301 <from> <to>")
 *   - dist/<from>/index.html  (universal HTML meta-refresh stub w/ canonical)
 *
 * No-op for brands without redirects.json or with an empty `permanent` list.
 *
 * Wiring: runs in scripts/run-build.mjs after `prune-dist.mjs` (which
 * removes any dist/<from>/ paths that aren't in the brand's route map).
 * Putting redirects AFTER prune means stubs aren't deleted; running BEFORE
 * astro build won't help because astro build doesn't know about redirects.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync, appendFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, '..');

const brand = process.env.BRAND;
if (!brand) {
  console.error('build-redirects: BRAND env var is required');
  process.exit(1);
}

const redirectsPath = join(projectRoot, '..', 'arich-source', 'content', 'brands', brand, 'redirects.json');
const distRoot = join(projectRoot, 'dist');

if (!existsSync(redirectsPath)) {
  console.log(`build-redirects: ${brand} has no redirects.json — skipping`);
  process.exit(0);
}

let parsed;
try {
  parsed = JSON.parse(readFileSync(redirectsPath, 'utf-8'));
} catch (err) {
  console.error(`build-redirects: failed to parse redirects.json — ${err.message}`);
  process.exit(1);
}

const entries = Array.isArray(parsed?.permanent) ? parsed.permanent : [];
if (entries.length === 0) {
  console.log(`build-redirects: ${brand} redirects.json is empty — no stubs emitted`);
  process.exit(0);
}

if (!existsSync(distRoot)) {
  console.error(`build-redirects: dist/ not found at ${distRoot} — astro build must run first`);
  process.exit(1);
}

/* ---------- read brand.json for absolute canonical in HTML stubs ---------- */
let brandUrl = '';
try {
  const brandJson = JSON.parse(readFileSync(
    join(projectRoot, '..', 'arich-source', 'content', 'brands', brand, 'brand.json'),
    'utf-8',
  ));
  brandUrl = (brandJson.url ?? '').replace(/\/$/, '');
} catch {
  /* brandUrl optional — HTML stubs still emit with relative canonical */
}

/* ---------- emit _redirects ---------- */
const netlifyLines = entries
  .filter((e) => e && typeof e.from === 'string' && typeof e.to === 'string')
  .map((e) => `${e.from} ${e.to} 301`)
  .join('\n') + '\n';
writeFileSync(join(distRoot, '_redirects'), netlifyLines);

/* ---------- emit .htaccess (append; respect any existing) ---------- */
const htaccessLines = entries
  .filter((e) => e && typeof e.from === 'string' && typeof e.to === 'string')
  .map((e) => `Redirect 301 ${e.from} ${e.to}`)
  .join('\n') + '\n';
const htaccessPath = join(distRoot, '.htaccess');
const banner = '# --- redirects (generated by build-redirects.mjs) ---\n';
const trailer = '# --- end redirects ---\n';
let existing = existsSync(htaccessPath) ? readFileSync(htaccessPath, 'utf-8') : '';
/* Strip any prior generated block so re-runs are idempotent. */
const re = new RegExp(banner.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + trailer.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
existing = existing.replace(re, '');
writeFileSync(htaccessPath, existing + banner + htaccessLines + trailer);

/* ---------- emit per-path HTML stubs ---------- */
let htmlCount = 0;
for (const e of entries) {
  if (!e || typeof e.from !== 'string' || typeof e.to !== 'string') continue;
  const from = e.from.replace(/\/+$/, '');
  if (!from.startsWith('/')) continue;
  const dir = join(distRoot, from);
  const file = join(dir, 'index.html');
  const absoluteTo = e.to.startsWith('http') ? e.to : `${brandUrl}${e.to}`;
  const canonical = absoluteTo || e.to;
  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Redirecting…</title>
  <link rel="canonical" href="${canonical}">
  <meta http-equiv="refresh" content="0; url=${e.to}">
  <meta name="robots" content="noindex">
</head>
<body>
  <p>Redirecting to <a href="${e.to}">${e.to}</a>…</p>
</body>
</html>
`;
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, html);
  htmlCount++;
}

console.log(`build-redirects: ${brand} emitted ${entries.length} redirect(s) — _redirects, .htaccess, ${htmlCount} HTML stub(s)`);
