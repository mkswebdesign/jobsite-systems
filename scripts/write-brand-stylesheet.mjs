#!/usr/bin/env node
/**
 * Writes `src/builder/styles/brands/_current.css` as a single `@import`
 * pointing at the stylesheet for $BRAND. The global stylesheet (global.css)
 * imports `_current.css` last, so whatever brand is building gets the final
 * cascade layer. Missing-brand → writes an empty stub so the build still
 * succeeds (shared CSS alone renders a usable site).
 *
 * Rationale: shared CSS under src/builder/styles/ is consumed by every
 * brand. Brand-specific visual overrides live in brands/<id>.css and only
 * load for that brand's build. This preserves the rule: "only editor +
 * file-structure management syncs across brands; visual decisions stay
 * per-brand."
 *
 * Runs as a prebuild step; idempotent; safe to run with no $BRAND set.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const brand = process.env.BRAND || 'arich';
const brandsDir = join(projectRoot, 'src', 'builder', 'styles', 'brands');
const currentCss = join(brandsDir, '_current.css');
const brandCss = join(brandsDir, `${brand}.css`);

const header = `/* AUTO-GENERATED by scripts/write-brand-stylesheet.mjs. Do not edit.\n * Current brand: ${brand}\n */\n`;

let body;
if (existsSync(brandCss)) {
  body = `@import './${brand}.css';\n`;
} else {
  body = `/* No brand override stylesheet found for "${brand}" — using shared defaults only. */\n`;
}

writeFileSync(currentCss, header + body, 'utf-8');
console.log(`brand stylesheet: brand=${brand} → brands/_current.css ${existsSync(brandCss) ? '(imports ' + brand + '.css)' : '(empty — no override file)'}`);
